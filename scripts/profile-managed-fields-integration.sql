CREATE FUNCTION private.write_audit(
  p_action text,
  p_entity_type text,
  p_entity_id text,
  p_reason text DEFAULT NULL,
  p_before jsonb DEFAULT NULL,
  p_after jsonb DEFAULT NULL,
  p_request_id text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'private'
