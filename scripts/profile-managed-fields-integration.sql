    auth.uid(), p_action, p_entity_type, p_entity_id, p_reason,
    p_before, p_after, p_request_id
  );
END;
$function$;

-- Copied from the read-only production definitions: this verifies the guard
-- against the actual RPC bodies rather than a synthetic test-only bypass.
CREATE FUNCTION public.admin_set_user_status(
  p_user_id uuid,
  p_status public.user_status,
  p_reason text DEFAULT NULL
)
RETURNS public.profiles
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'private'
AS $function$
DECLARE
  v_before public.profiles;
  v_after public.profiles;
BEGIN
  IF NOT private.current_user_is_admin() THEN
    RAISE EXCEPTION 'ACCESS_DENIED';
  END IF;

  SELECT * INTO v_before
  FROM public.profiles
  WHERE id = p_user_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'USER_NOT_FOUND';
  END IF;

  UPDATE public.profiles
  SET status = p_status, updated_at = now()
  WHERE id = p_user_id
  RETURNING * INTO v_after;

  PERFORM private.write_audit(
    'user.status_update', 'user', p_user_id::text, p_reason,
    to_jsonb(v_before), to_jsonb(v_after), NULL
  );
  RETURN v_after;
END;
$function$;

CREATE FUNCTION public.set_profile_verification(p_user_id uuid, p_type text)
RETURNS public.profiles
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'private'
AS $function$
DECLARE
  v_profile public.profiles;
BEGIN
  IF auth.uid() IS NULL OR NOT private.current_user_is_admin() THEN
    RAISE EXCEPTION 'ACCESS_DENIED';
  END IF;

  IF p_type IS NOT NULL AND p_type NOT IN ('blue', 'gold', 'orange', 'admin-shield') THEN
    RAISE EXCEPTION 'INVALID_VERIFICATION_TYPE';
  END IF;

  UPDATE public.profiles
  SET verification_type = p_type, updated_at = now()
  WHERE id = p_user_id
  RETURNING * INTO v_profile;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'USER_NOT_FOUND';
  END IF;

  RETURN v_profile;
END;
$function$;

